def resolve_parts(
    db: Session,
    active_org_id: int,
    user: Any,
    session_ids: Iterable[Any],
) -> list[Any]:
    """Resolve wire ids to sessions the caller may EDIT, validate the set and
    return the parts in time order. Raises ``CombineError`` (400 / 404)."""
    from api.session_permissions import resolve_session_for_user

    wanted: list[str] = []
    seen: set[str] = set()
    for raw in session_ids or []:
        key = str(raw).strip()
        if not key or key in seen:
            continue
        seen.add(key)
        wanted.append(key)
    if len(wanted) < 2:
        raise CombineError(400, "At least two distinct sessions are required")

    parts: list[Any] = []
    seen_pk: set[int] = set()
    for key in wanted:
        session = resolve_session_for_user(db, active_org_id, key, user, min_level="edit")
        if session is None:
            # Not found OR not editable by this caller — the same answer, so
            # we never confirm the existence of a session the caller can't see.
            raise CombineError(404, f"Session {key} not found")
        if session.id in seen_pk:
            continue  # the same row referenced by UUID and by pk
        seen_pk.add(session.id)
        parts.append(session)
    if len(parts) < 2:
        raise CombineError(400, "At least two distinct sessions are required")
    if any(bool(getattr(p, "is_combined", False)) for p in parts):
        raise CombineError(
            400, "A combined meeting cannot be a part of another combined meeting"
        )
    if len({p.organization_id for p in parts}) != 1:
        raise CombineError(400, "All sessions must belong to the same organization")
    return order_parts(parts)


def _union_participants(parts: list[Any]) -> list[dict]:
    out: list[dict] = []
    seen: set[tuple[str, str]] = set()
    for part in parts:
        for entry in (getattr(part, "participants", None) or []):
            if not isinstance(entry, dict):
                continue
            key = (
                (entry.get("name") or "").strip().lower(),
                (entry.get("email") or "").strip().lower(),
            )
            if key == ("", "") or key in seen:
                continue
            seen.add(key)
            out.append(dict(entry))
    return out


def _union_tags(parts: list[Any]) -> list[str]:
    out: list[str] = []
    for part in parts:
        for tag in (getattr(part, "tags", None) or []):
            if tag and tag not in out:
                out.append(tag)
    return out


def create_combined_session(
    db: Session,
    parts: list[Any],
    *,
    name: Optional[str],
    user_id: Optional[int],
) -> Any:
    """Create the combined row + ordered link rows. Status starts as
    ``processing``; the worker flips it to ``completed`` / ``failed``."""
    from database.models import RecordingSession, SessionGroupMember

    parts = order_parts(parts)
    first = parts[0]
    starts = [s for s in (part_start(p) for p in parts) if s is not None]
    ends = [e for e in (part_end(p) for p in parts) if e is not None]
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    started = min(starts) if starts else now
    ended = max(ends) if ends else None
    duration = float(sum(float(p.duration or 0) for p in parts))

    clean_name = (name or "").strip()
    user_named = bool(clean_name)
    if not user_named:
        clean_name = default_name(parts)
    clean_name = clean_name[:200]

    combined = RecordingSession(
        session_id=str(uuid.uuid4()),
        name=clean_name,
        title=clean_name,
        # A user-supplied name is final; the default one may be replaced by
        # the summarizer's title suggestion, exactly like an upload.
        title_user_set=user_named,
        description=(
            f"Combined meeting of {len(parts)} recordings: "
            + "; ".join(display_name(p) for p in parts)
        )[:2000],
        status="processing",
        organization_id=first.organization_id,
        user_id=user_id,
        # created_at follows the meeting's own timeline (the rule uploads use
        # since the recorded-at fix) so the combined row sorts next to its
        # parts instead of at "today". Watchdog sweeps key combined rows on
        # updated_at for that reason.
        created_at=started,
        started_at=started,
        ended_at=ended,
        duration=duration,
        meeting_date=first.meeting_date or started.date(),
        meeting_time=first.meeting_time or started.time().replace(microsecond=0),
        is_combined=True,
        participants=_union_participants(parts),
        tags=_union_tags(parts),
        processing_metadata={
            "combined": {
                "parts": [p.id for p in parts],
                "created_at": datetime.now(timezone.utc).isoformat(),
            }
        },
    )
    db.add(combined)
    db.flush()
    for position, part in enumerate(parts):
        db.add(
            SessionGroupMember(
                combined_session_id=combined.id,
                member_session_id=part.id,
                position=position,
            )
        )
    db.commit()
    db.refresh(combined)
    return combined


