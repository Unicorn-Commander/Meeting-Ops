"""Combined meetings — glue between the API, the DB and the summarizer.

A *combined meeting* (docs/COMBINED-MEETINGS-CONTRACT.md) is a summary-only
``recording_sessions`` row (``is_combined = true``) that points at its parts
through ``session_group_members`` in time order. Parts are never modified:
they keep their own audio, transcript, speakers and player. The combined row
owns only the unified summary / insights / action items, generated by the
SAME summarizer the finalize path uses, over a transcript assembled here from
the parts' speaker turns with a boundary marker line between parts.

Wire ids: the UI addresses sessions by ``session_id`` (UUID) when set, else
the integer pk as a string — every ``id`` emitted here follows that rule.

Models are imported lazily inside functions on purpose: the test fixture
reloads ``database.models`` after collection, and a module-level import here
would pin the stale classes (same reason ``workers/finalize_workers.py`` does
its imports inside the job).
"""

from __future__ import annotations

import logging
import re
import uuid
from datetime import datetime, timedelta, timezone
from types import SimpleNamespace
from typing import Any, Iterable, Optional

from sqlalchemy import func
from sqlalchemy.orm import Session

logger = logging.getLogger(__name__)

# Our normalized generic label ("Speaker 3"). Generic labels are per-part
# diarizer output, so "Speaker 1" in part 1 and "Speaker 1" in part 2 are NOT
# necessarily the same person — they get a "(part k)" suffix in the combined
# transcript. Real names are consistent across parts and stay untouched.
_GENERIC_SPEAKER_RE = re.compile(r"^Speaker \d+$")


class CombineError(Exception):
    """Validation failure the API maps onto an HTTP status + detail."""

    def __init__(self, status_code: int, detail: str):
        super().__init__(detail)
        self.status_code = status_code
        self.detail = detail


# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------


def wire_id(session: Any) -> str:
    """The id the UI uses for a session: ``session_id`` (UUID) else the pk."""
    return session.session_id or str(session.id)


def display_name(session: Any) -> str:
    return (session.name or session.title or f"Session {session.id}").strip()


def _naive_utc(dt: Optional[datetime]) -> Optional[datetime]:
    if dt is None:
        return None
    if dt.tzinfo is not None:
        return dt.astimezone(timezone.utc).replace(tzinfo=None)
    return dt


def part_start(part: Any) -> Optional[datetime]:
    return _naive_utc(getattr(part, "started_at", None) or getattr(part, "created_at", None))


def part_end(part: Any) -> Optional[datetime]:
    ended = _naive_utc(getattr(part, "ended_at", None))
    if ended is not None:
        return ended
    start = part_start(part)
    if start is None:
        return None
    return start + timedelta(seconds=float(getattr(part, "duration", 0) or 0))


def order_parts(parts: Iterable[Any]) -> list[Any]:
    """Time order: ``started_at`` (falls back to ``created_at``), ties by id."""
    return sorted(parts, key=lambda p: (part_start(p) or datetime.max, int(p.id)))


def default_name(parts_in_order: list[Any]) -> str:
    first = parts_in_order[0]
    return f"{display_name(first)} (combined, {len(parts_in_order)} parts)"[:200]


