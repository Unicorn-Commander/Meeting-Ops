def members_in_order(db: Session, combined_id: int) -> list[tuple[Any, Any]]:
    from database.models import RecordingSession, SessionGroupMember

    return (
        db.query(SessionGroupMember, RecordingSession)
        .join(RecordingSession, RecordingSession.id == SessionGroupMember.member_session_id)
        .filter(SessionGroupMember.combined_session_id == combined_id)
        .order_by(
            SessionGroupMember.position.asc(),
            SessionGroupMember.member_session_id.asc(),
        )
        .all()
    )


def _part_dict(part: Any, position: Optional[int] = None) -> dict:
    start = part_start(part)
    payload = {
        "id": wire_id(part),
        "pk": int(part.id),
        "name": display_name(part),
        "started_at": start.isoformat() if start else None,
        "duration": float(part.duration or 0),
        "status": part.status or "completed",
        "meeting_date": part.meeting_date.isoformat() if part.meeting_date else None,
        "meeting_time": part.meeting_time.isoformat() if part.meeting_time else None,
    }
    if position is not None:
        payload["position"] = position
    return payload


def parts_payload(db: Session, combined: Any) -> list[dict]:
    return [
        _part_dict(part, member.position)
        for member, part in members_in_order(db, combined.id)
    ]


def part_of_payload(db: Session, session: Any) -> list[dict]:
    from database.models import RecordingSession, SessionGroupMember

    rows = (
        db.query(RecordingSession)
        .join(SessionGroupMember, SessionGroupMember.combined_session_id == RecordingSession.id)
        .filter(SessionGroupMember.member_session_id == session.id)
        .order_by(RecordingSession.id.asc())
        .all()
    )
    return [{"id": wire_id(c), "pk": int(c.id), "name": display_name(c)} for c in rows]


def combine_meta_batch(db: Session, sessions: list[Any]) -> dict[int, dict]:
    """Two round-trips for a whole list page:
    ``{pk: {"is_combined", "parts_count", "part_of"}}``."""
    from database.models import RecordingSession, SessionGroupMember

    meta = {
        int(s.id): {
            "is_combined": bool(getattr(s, "is_combined", False)),
            "parts_count": 0,
            "part_of": [],
        }
        for s in sessions
    }
    if not meta:
        return meta
    ids = list(meta)
    for combined_id, count in (
        db.query(
            SessionGroupMember.combined_session_id,
            func.count(SessionGroupMember.member_session_id),
        )
        .filter(SessionGroupMember.combined_session_id.in_(ids))
        .group_by(SessionGroupMember.combined_session_id)
        .all()
    ):
        meta[int(combined_id)]["parts_count"] = int(count)
    for member_id, combined in (
        db.query(SessionGroupMember.member_session_id, RecordingSession)
        .join(RecordingSession, RecordingSession.id == SessionGroupMember.combined_session_id)
        .filter(SessionGroupMember.member_session_id.in_(ids))
        .order_by(RecordingSession.id.asc())
        .all()
    ):
        meta[int(member_id)]["part_of"].append(
            {"id": wire_id(combined), "pk": int(combined.id), "name": display_name(combined)}
        )
    return meta


def detail_fields(db: Session, session: Any) -> dict:
    """Fields the session DETAIL payload gains (contract)."""
    fields: dict[str, Any] = {
        "is_combined": bool(getattr(session, "is_combined", False)),
        "part_of": part_of_payload(db, session),
    }
    if fields["is_combined"]:
        fields["parts"] = parts_payload(db, session)
    return fields


def combined_payload(db: Session, combined: Any, *, job_id: Optional[str] = None) -> dict:
    """202 body for combine / rerun."""
    payload = {
        "id": wire_id(combined),
        "pk": int(combined.id),
        "session_id": wire_id(combined),
        "name": display_name(combined),
        "status": combined.status or "processing",
        "is_combined": True,
        "parts": parts_payload(db, combined),
        "status_url": f"/api/simple/recording-sessions/{wire_id(combined)}",
    }
    if job_id:
        payload["job_id"] = job_id
    return payload


