def _part_segments(db: Session, part: Any) -> list[dict]:
    """A part's speaker turns as plain dicts, in time order. Prefers the
    diarized doc (what the summarizer uses for the part itself), then the
    ``transcriptions`` rows the UI renders, then the flat transcript."""
    from database.models import Transcription

    diarized = getattr(part, "transcript_diarized", None)
    raw_segments = diarized.get("segments") if isinstance(diarized, dict) else None
    out: list[dict] = []
    if raw_segments:
        for seg in raw_segments:
            if not isinstance(seg, dict):
                continue
            text = (seg.get("text") or "").strip()
            if not text:
                continue
            start = float(seg.get("start") or 0)
            out.append(
                {
                    "speaker": (seg.get("speaker") or "").strip(),
                    "text": text,
                    "start": start,
                    "end": float(seg.get("end") or start),
                }
            )
        if out:
            return out
    rows = (
        db.query(Transcription)
        .filter(Transcription.session_id == part.id)
        .order_by(Transcription.start_time.asc(), Transcription.id.asc())
        .all()
    )
    for row in rows:
        text = (row.text or "").strip()
        if not text:
            continue
        start = float(row.start_time or 0)
        out.append(
            {
                "speaker": (row.speaker or "").strip(),
                "text": text,
                "start": start,
                "end": float(row.end_time or start),
            }
        )
    if out:
        return out
    flat = (getattr(part, "transcript_simple", None) or "").strip()
    if flat:
        return [{"speaker": "", "text": flat, "start": 0.0, "end": float(part.duration or 0)}]
    return []


def _relabel(segments: list[dict], part_index: int, n_parts: int) -> None:
    """Raw diarizer codes -> "Speaker N" exactly like the summarizer does for
    a single session, then suffix GENERIC labels with the part they came from
    (per-part diarization means the numbers don't line up across recordings)."""
    from services.speaker_labels import normalized_label_map

    label_map = normalized_label_map([s["speaker"] for s in segments])
    for seg in segments:
        raw = seg["speaker"]
        display = label_map.get(raw, raw) if raw else ""
        if display and n_parts > 1 and _GENERIC_SPEAKER_RE.match(display):
            display = f"{display} (part {part_index})"
        seg["speaker"] = display


def _mmss(seconds: float) -> str:
    total = int(max(0.0, float(seconds or 0)))
    return f"{total // 60:02d}:{total % 60:02d}"


def marker_text(part_index: int, n_parts: int, part: Any) -> str:
    start = part_start(part)
    when = start.strftime("%Y-%m-%d %H:%M UTC") if start else "time unknown"
    return (
        f"=== Part {part_index} of {n_parts}: {display_name(part)} — {when} "
        f"({_mmss(part.duration or 0)}) ==="
    )


def build_combined_transcript(db: Session, combined: Any) -> dict:
    """Assemble the combined transcript from the parts in position order.

    Returns ``segments`` (diarized-doc shape; boundary markers carry
    ``kind="marker"``; times are offset onto one continuous timeline),
    ``speakers`` (display labels, first appearance), ``text`` (the
    speaker-attributed transcript the summarizer's fallback + exports read),
    ``rows`` (Transcription-shaped objects for the insights speaker stats)
    and ``parts``.
    """
    from services.speaker_labels import build_attributed_transcript

    members = members_in_order(db, combined.id)
    parts = [part for _member, part in members]
    n_parts = len(parts)
    segments: list[dict] = []
    speakers: list[str] = []
    rows: list[SimpleNamespace] = []
    offset = 0.0
    for index, part in enumerate(parts, start=1):
        part_segments = _part_segments(db, part)
        _relabel(part_segments, index, n_parts)
        segments.append(
            {
                "kind": "marker",
                "speaker": "",
                "text": marker_text(index, n_parts, part),
                "start": offset,
                "end": offset,
                "part": index,
                "part_session_id": wire_id(part),
            }
        )
        last_end = 0.0
        for seg in part_segments:
            shifted = {
                "speaker": seg["speaker"],
                "text": seg["text"],
                "start": seg["start"] + offset,
                "end": seg["end"] + offset,
                "part": index,
            }
            segments.append(shifted)
            last_end = max(last_end, seg["end"])
            if shifted["speaker"] and shifted["speaker"] not in speakers:
                speakers.append(shifted["speaker"])
            rows.append(
                SimpleNamespace(
                    speaker=shifted["speaker"] or None,
                    text=shifted["text"],
                    start_time=shifted["start"],
                    end_time=shifted["end"],
                )
            )
        offset += max(float(part.duration or 0), last_end)
    text, _seen = build_attributed_transcript(segments)
    return {
        "segments": segments,
        "speakers": speakers,
        "text": text,
        "rows": rows,
        "parts": parts,
    }


def apply_combined_transcript(session: Any, built: dict) -> None:
    """Write the assembled transcript onto the combined row (NOT into the
    ``transcriptions`` table — the parts own those rows)."""
    session.transcript_diarized = {
        "segments": built["segments"],
        "speakers": list(built["speakers"]),
        "source": "combined",
    }
    session.transcript_simple = built["text"]
