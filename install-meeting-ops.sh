#!/usr/bin/env bash
# Meeting-Ops local self-host installer.
#
# This script is intentionally Docker-only. It creates deployment secrets and
# the first local admin at install time; no credential is stored in the repo.

set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/.env"
COMPOSE_FILE="$SCRIPT_DIR/docker-compose.selfhost.yml"
API_URL="http://127.0.0.1:9050"
WEB_URL="http://127.0.0.1:7777"

cd "$SCRIPT_DIR"
umask 077

die() {
  echo "[ERROR] $*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "Missing required command: $1"
}

generate_secret() {
  openssl rand -hex 32
}

generate_admin_username() {
  printf 'admin_%s\n' "$(openssl rand -hex 5)"
}

generate_admin_password() {
  # The fixed prefix/suffix provide uppercase, lowercase, and numeric
  # characters; the middle is random and keeps the value shell-safe.
  printf 'M%sz9\n' "$(openssl rand -hex 24)"
}

read_env_value() {
  local key="$1"
  awk -F= -v wanted="$key" '$1 == wanted {sub(/^[^=]*=/, ""); print; exit}' "$ENV_FILE"
}

create_env_file() {
  if [ -e "$ENV_FILE" ]; then
    [ -f "$ENV_FILE" ] || die "$ENV_FILE exists but is not a regular file"
    chmod 600 "$ENV_FILE"
    for key in POSTGRES_PASSWORD REDIS_PASSWORD SECRET_KEY \
      MEETING_OPS_ADMIN_USERNAME MEETING_OPS_ADMIN_EMAIL MEETING_OPS_ADMIN_PASSWORD; do
      [ -n "$(read_env_value "$key")" ] || die "$ENV_FILE is missing $key; remove it and rerun or add that value"
    done
    return
  fi

  local admin_username
  local admin_email
  admin_username="$(generate_admin_username)"
  admin_email="${admin_username}@meeting-ops.local"

  cat > "$ENV_FILE" <<EOF
# Generated by install-meeting-ops.sh. Keep mode 0600; never commit this file.
COMPOSE_PROJECT_NAME=meeting-ops-selfhost
POSTGRES_PASSWORD=$(generate_secret)
REDIS_PASSWORD=$(generate_secret)
SECRET_KEY=$(generate_secret)
MEETING_OPS_ADMIN_USERNAME=${admin_username}
MEETING_OPS_ADMIN_EMAIL=${admin_email}
MEETING_OPS_ADMIN_PASSWORD=$(generate_admin_password)
APP_BASE_URL=http://127.0.0.1:7777
APP_PUBLIC_URL=http://127.0.0.1:7777
CORS_ORIGINS=http://127.0.0.1:7777,http://localhost:7777
MEETING_OPS_API_PORT=9050
MEETING_OPS_WEB_PORT=7777
MEETING_OPS_POSTGRES_PORT=5434
MEETING_OPS_REDIS_PORT=6381
EOF
  chmod 600 "$ENV_FILE"
}

require_command openssl
require_command curl
require_command docker
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required"
docker info >/dev/null 2>&1 || die "Docker is not running or this user cannot access it"
[ -f "$COMPOSE_FILE" ] || die "Missing $COMPOSE_FILE"

create_env_file

POSTGRES_PASSWORD="$(read_env_value POSTGRES_PASSWORD)"
REDIS_PASSWORD="$(read_env_value REDIS_PASSWORD)"
SECRET_KEY="$(read_env_value SECRET_KEY)"
ADMIN_USERNAME="$(read_env_value MEETING_OPS_ADMIN_USERNAME)"
ADMIN_EMAIL="$(read_env_value MEETING_OPS_ADMIN_EMAIL)"
ADMIN_PASSWORD="$(read_env_value MEETING_OPS_ADMIN_PASSWORD)"

for value in "$POSTGRES_PASSWORD" "$REDIS_PASSWORD" "$SECRET_KEY" \
  "$ADMIN_USERNAME" "$ADMIN_EMAIL" "$ADMIN_PASSWORD"; do
  [ -n "$value" ] || die "Generated .env contains an empty required value"
done

mkdir -p "$SCRIPT_DIR/data" "$SCRIPT_DIR/recordings"

compose=(docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE")
"${compose[@]}" config --quiet
echo "[INFO] Building and starting the local Meeting-Ops stack..."
"${compose[@]}" up -d --build

health_body="$(mktemp)"
ui_probe="$(mktemp)"
cleanup() {
  rm -f "$health_body" "$ui_probe"
}
trap cleanup EXIT

echo "[INFO] Waiting for API health at $API_URL/health..."
api_ready=false
for _ in $(seq 1 90); do
  if curl -fsS "$API_URL/health" >"$health_body" 2>/dev/null \
    && grep -Eq '"status"[[:space:]]*:[[:space:]]*"healthy"' "$health_body"; then
    api_ready=true
    break
  fi
  sleep 2
done

if [ "$api_ready" != true ]; then
  echo "[ERROR] API did not become healthy. Recent service status:" >&2
  "${compose[@]}" ps >&2 || true
  exit 1
fi

echo "[INFO] Waiting for web UI at $WEB_URL/..."
ui_ready=false
for _ in $(seq 1 30); do
  if curl -fsS "$WEB_URL/" >"$ui_probe" 2>/dev/null; then
    ui_ready=true
    break
  fi
  sleep 2
done
[ "$ui_ready" = true ] || die "Web UI did not become reachable at $WEB_URL/"

echo "[INFO] Creating the generated local bootstrap admin..."
"${compose[@]}" exec -T \
  -e MEETING_OPS_ADMIN_USERNAME="$ADMIN_USERNAME" \
  -e MEETING_OPS_ADMIN_EMAIL="$ADMIN_EMAIL" \
  -e MEETING_OPS_ADMIN_PASSWORD="$ADMIN_PASSWORD" \
  backend python - <<'PY'
import os

from auth.models import User
from auth.service import AuthService
from database.database import SessionLocal

username = os.environ["MEETING_OPS_ADMIN_USERNAME"]
email = os.environ["MEETING_OPS_ADMIN_EMAIL"]
password = os.environ["MEETING_OPS_ADMIN_PASSWORD"]

db = SessionLocal()
try:
    user = db.query(User).filter(User.username == username).first()
    if user is None:
        user = AuthService.create_user(
            db,
            email=email,
            username=username,
            password=password,
            role="admin",
            personal_org=True,
        )
        created = True
    else:
        if user.email != email:
            raise RuntimeError("bootstrap username already belongs to another email")
        created = False

    user.is_active = True
    user.is_verified = True
    user.is_superuser = True
    db.commit()
    print("bootstrap admin created" if created else "bootstrap admin already exists")
finally:
    db.close()
PY

cat <<EOF

[OK] Meeting-Ops is running.
    Web:             $WEB_URL
    API health:      $API_URL/health
    Admin username:  $ADMIN_USERNAME
    Admin password:  $ADMIN_PASSWORD

Store the generated admin credentials securely. The agent PAT route is
documented in README.md and INSTALL.md; this installer does not mint a PAT.
EOF
